const safe = v => v === null || v === undefined ? '' : String(v)

function addHeader(doc,{title,subtitle,company}){
 const width=doc.internal.pageSize.getWidth()-28
 doc.setFont('helvetica','bold');doc.setFontSize(16)
 const names=doc.splitTextToSize(company?.name||'General Hardware',width);doc.text(names,14,16)
 let y=16+names.length*6
 doc.setFont('helvetica','normal');doc.setFontSize(8)
 const contact=[company?.town,company?.country,company?.phone,company?.email].filter(Boolean).join(' · ')
 if(contact){const lines=doc.splitTextToSize(contact,width);doc.text(lines,14,y);y+=lines.length*4}
 doc.setFont('helvetica','bold');doc.setFontSize(12);const titles=doc.splitTextToSize(title,width);doc.text(titles,14,y+3);y+=titles.length*5+3
 doc.setFont('helvetica','normal');doc.setFontSize(8)
 if(subtitle){const lines=doc.splitTextToSize(subtitle,width);doc.text(lines,14,y+2);y+=lines.length*4+2}
 doc.setDrawColor(180);doc.line(14,y+3,doc.internal.pageSize.getWidth()-14,y+3)
 return y+8
}

function addFooter(doc,footer){
  const pages=doc.getNumberOfPages()
  for(let i=1;i<=pages;i++){
    doc.setPage(i)
    doc.setFontSize(8); doc.setTextColor(110)
    doc.text(footer||'Generated by GH Procurement',14,doc.internal.pageSize.getHeight()-8)
    doc.text(`Page ${i} of ${pages}`,doc.internal.pageSize.getWidth()-14,doc.internal.pageSize.getHeight()-8,{align:'right'})
    doc.setTextColor(0)
  }
}

export function exportTablePdf({filename,title,subtitle,columns,rows,company,footer,note,orientation='landscape'}){
  const doc=new jsPDF({orientation,unit:'mm',format:'a4'})
  const startY=addHeader(doc,{title,subtitle,company})
  autoTable(doc,{
    startY,
    head:[columns.map(c=>safe(c.label||c.key))],
    body:rows.map(r=>columns.map(c=>safe(typeof c.value==='function'?c.value(r):r[c.key]))),
    styles:{fontSize:7.5,cellPadding:2,overflow:'linebreak'},
    headStyles:{fillColor:[31,41,55],textColor:255,fontStyle:'bold'},
    alternateRowStyles:{fillColor:[248,250,252]},
    margin:{left:10,right:10,bottom:16},
    didDrawPage:()=>{}
  })
  if(note){doc.setFontSize(8);const lines=doc.splitTextToSize(note,doc.internal.pageSize.getWidth()-28);let y=(doc.lastAutoTable?.finalY||startY)+6;if(y+lines.length*4>doc.internal.pageSize.getHeight()-18){doc.addPage();y=20}doc.text(lines,14,y)}
  addFooter(doc,footer)
  doc.save(filename)
}

