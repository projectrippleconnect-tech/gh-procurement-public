import {STOCK_PRINT_COLUMNS,resolveStockPrint} from './stock-print.mjs'
import {purchaseOrderShareModel} from './po-share.js'
import { jsPDF } from 'jspdf'
import { autoTable } from 'jspdf-autotable'

const safe = v => v === null || v === undefined ? '' : String(v)

function addHeader(doc,{title,subtitle,company}){
 const width=doc.internal.pageSize.getWidth()-28
 doc.setFont('helvetica','bold');doc.setFontSize(16)
 const names=doc.splitTextToSize(company?.name||'General Hardware',width);doc.text(names,14,16)
 let y=16+names.length*6
 doc.setFont('helvetica','normal');doc.setFontSize(8)
 const contact=[company?.town,company?.country,company?.phone,company?.email].filter(Boolean).join(' · ')
 if(contact){const lines=doc.splitTextToSize(contact,width);doc.text(lines,14,y);y+=lines.length*4}
 doc.setFont('helvetica','bold');doc.setFontSize(12);const titles=doc.splitTextToSize(title,width);doc.text(titles,14,y+3);y+=titles.length*5+3
 doc.setFont('helvetica','normal');doc.setFontSize(8)
 if(subtitle){const lines=doc.splitTextToSize(subtitle,width);doc.text(lines,14,y+2);y+=lines.length*4+2}
 doc.setDrawColor(180);doc.line(14,y+3,doc.internal.pageSize.getWidth()-14,y+3)
 return y+8
}

function addFooter(doc,footer){
  const pages=doc.getNumberOfPages()
  for(let i=1;i<=pages;i++){
    doc.setPage(i)
    doc.setFontSize(8); doc.setTextColor(110)
    doc.text(footer||'Generated by GH Procurement',14,doc.internal.pageSize.getHeight()-8)
    doc.text(`Page ${i} of ${pages}`,doc.internal.pageSize.getWidth()-14,doc.internal.pageSize.getHeight()-8,{align:'right'})
    doc.setTextColor(0)
  }
}

export function exportTablePdf({filename,title,subtitle,columns,rows,company,footer,note,orientation='landscape'}){
  const doc=new jsPDF({orientation,unit:'mm',format:'a4'})
  const startY=addHeader(doc,{title,subtitle,company})
  autoTable(doc,{
    startY,
    head:[columns.map(c=>safe(c.label||c.key))],
    body:rows.map(r=>columns.map(c=>safe(typeof c.value==='function'?c.value(r):r[c.key]))),
    styles:{fontSize:7.5,cellPadding:2,overflow:'linebreak'},
    headStyles:{fillColor:[31,41,55],textColor:255,fontStyle:'bold'},
    alternateRowStyles:{fillColor:[248,250,252]},
    margin:{left:10,right:10,bottom:16},
    didDrawPage:()=>{}
  })
  if(note){doc.setFontSize(8);const lines=doc.splitTextToSize(note,doc.internal.pageSize.getWidth()-28);let y=(doc.lastAutoTable?.finalY||startY)+6;if(y+lines.length*4>doc.internal.pageSize.getHeight()-18){doc.addPage();y=20}doc.text(lines,14,y)}
  addFooter(doc,footer)
  doc.save(filename)
}

export function exportSupplierPriceRequestPdf({rfq,items,supplier,company,footer}){
  const supplierName=supplier?.name||'Supplier'
  const clean=v=>String(v||'').replace(/[^a-zA-Z0-9_-]+/g,'-').replace(/^-|-$/g,'')
  exportTablePdf({
    filename:`${clean(rfq?.rfq_no||'RFQ')}-${clean(supplierName)||'supplier'}.pdf`,
    title:company?.documentTitle||'REQUEST FOR QUOTATION',
    subtitle:[rfq?.rfq_no,supplierName,rfq?.due_date?'Reply by '+rfq.due_date:null].filter(Boolean).join(' · '),
    company,footer,note:company?.documentNote,orientation:'portrait',
    columns:[
      {key:'no',label:'#',value:r=>r.no},
      {key:'qty',label:'Qty',value:r=>r.qty},
      {key:'uom',label:'UOM',value:r=>r.uom},
      {key:'item',label:'Item / Size',value:r=>r.item},
      {key:'price',label:'Unit Rate',value:()=>''},
      {key:'available',label:'Available',value:()=>''},
      {key:'lead',label:'Delivery / Lead Time',value:()=>''}
    ].filter(c=>!['no','uom','price'].includes(c.key)||company?.documentTemplate?.fields?.[c.key==='price'?'rate':c.key]!==false),
    rows:(items||[]).map((x,index)=>{
      const item=x.requirement?.item||x.item||{}
      return {
        no:index+1,
        item:[item.description,item.size].filter(Boolean).join(' · '),
        uom:item.uom||'',
        qty:x.requested_qty??x.qty??''
      }
    })
  })
}

export function exportPurchaseOrderPdf({po,lines,company,footer,selection}){
  const m=purchaseOrderShareModel({po,lines,company,selection})
  const doc=new jsPDF({orientation:m.columns.length>6?'landscape':'portrait',unit:'mm',format:'a4'})
  let y=addHeader(doc,{title:m.title,subtitle:po.po_no,company})
  doc.setFontSize(9)
  for(const [k,v] of m.meta){
    const wrapped=doc.splitTextToSize(v,doc.internal.pageSize.getWidth()-65)
    doc.setFont('helvetica','bold');doc.text(k,14,y)
    doc.setFont('helvetica','normal');doc.text(wrapped,48,y)
    y+=Math.max(6,wrapped.length*5)
  }
  autoTable(doc,{startY:y+2,head:[m.columns.map(c=>c.label)],body:m.rows,
    styles:{fontSize:8,cellPadding:2,overflow:'linebreak'},headStyles:{fillColor:[31,41,55],textColor:255},margin:{left:14,right:14,bottom:30}})
  if(m.note){const note=doc.splitTextToSize(m.note,doc.internal.pageSize.getWidth()-28);let ny=(doc.lastAutoTable?.finalY||y)+6;if(ny+note.length*4>doc.internal.pageSize.getHeight()-32){doc.addPage();ny=20}doc.setFontSize(8);doc.text(note,14,ny);doc.lastAutoTable.finalY=ny+note.length*4}
  if(m.total){let fy=(doc.lastAutoTable?.finalY||y)+8;if(fy>doc.internal.pageSize.getHeight()-32){doc.addPage();fy=20}
    doc.setFont('helvetica','bold');doc.text('TOTAL: '+m.total,doc.internal.pageSize.getWidth()-14,fy,{align:'right'})}
  for(let page=1;page<=doc.getNumberOfPages();page++){doc.setPage(page);addStockApprovalFooter(doc)}
  addFooter(doc,footer)
  doc.save(`${String(po.po_no||'Purchase-Order').replace(/[^a-zA-Z0-9_-]/g,'-')}.pdf`)
}

function addStockApprovalFooter(doc){
  const pageW=doc.internal.pageSize.getWidth()
  const pageH=doc.internal.pageSize.getHeight()
  const y=pageH-18
  const left=12
  const right=pageW-12
  const gap=4
  const dateW=28
  const sigW=(right-left-dateW-gap*3)/3
  const fields=[
    ['Stocks Checked By',sigW],
    ['Stocks Verified By',sigW],
    ['Order Approved By',sigW],
    ['Date',dateW],
  ]
  let x=left
  doc.setFont('helvetica','normal');doc.setFontSize(7.5);doc.setTextColor(70)
  for(const [label,w] of fields){
    doc.setDrawColor(150);doc.line(x,y,x+w,y)
    doc.text(label,x+w/2,y+4,{align:'center'})
    x+=w+gap
  }
  doc.setTextColor(0)
}

function stockPageHeader(doc,{company,title,subtitle,pageNo,totalPages}){
  const pageW=doc.internal.pageSize.getWidth()
  const name=company?.name||'General Hardware'
  doc.setFont('helvetica','bold');doc.setFontSize(13);doc.text(name,12,12)
  doc.setFont('helvetica','normal');doc.setFontSize(7.5)
  doc.text([company?.town,company?.country].filter(Boolean).join(' · '),12,17)
  doc.setFont('helvetica','bold');doc.setFontSize(11);doc.text(title,pageW-12,12,{align:'right'})
  doc.setFont('helvetica','normal');doc.setFontSize(7.5)
  if(subtitle)doc.text(subtitle,pageW-12,17,{align:'right'})
  doc.text(`Page ${pageNo} of ${totalPages}`,pageW-12,22,{align:'right'})
  doc.setDrawColor(170);doc.line(12,25,pageW-12,25)
}

function exportThreeTableStockPdf({filename,title,subtitle,company,items,columns,rowBuilder,rowsPerTable=10,tablesPerPage=3}){
  const doc=new jsPDF({orientation:'portrait',unit:'mm',format:'a4'})
  tablesPerPage=Math.max(1,Math.min(Number(tablesPerPage)||3,4))
  rowsPerTable=Math.max(5,Math.min(Number(rowsPerTable)||10,25))
  const perPage=rowsPerTable*tablesPerPage
  const totalPages=Math.max(1,Math.ceil(items.length/perPage))
  const starts=tablesPerPage===3?[30,105,180]:Array.from({length:tablesPerPage},(_,i)=>30+i*((250-30)/tablesPerPage))

  for(let p=0;p<totalPages;p++){
    if(p>0)doc.addPage()
    stockPageHeader(doc,{company,title,subtitle,pageNo:p+1,totalPages})
    const pageItems=items.slice(p*perPage,(p+1)*perPage)

    for(let t=0;t<tablesPerPage;t++){
      const chunk=pageItems.slice(t*rowsPerTable,(t+1)*rowsPerTable)
      const padded=[...chunk]
      while(padded.length<rowsPerTable)padded.push(null)
      autoTable(doc,{
        startY:starts[t],
        head:[columns.map(c=>c.label)],
        body:padded.map((item,idx)=>item?rowBuilder(item,p*perPage+t*rowsPerTable+idx+1):columns.map(()=>'')),
        theme:'grid',
        styles:{fontSize:7.4,cellPadding:1.4,minCellHeight:5.3,overflow:'linebreak',valign:'middle'},
        headStyles:{fillColor:[31,41,55],textColor:255,fontStyle:'bold',minCellHeight:5.5},
        margin:{left:12,right:12},
        tableWidth:'auto',
        pageBreak:'avoid',
        rowPageBreak:'avoid'
      })
    }
    addStockApprovalFooter(doc)
  }
  doc.save(filename)
}

export function exportMovementChecklistPdf({items,company,movement='FAST',category='',title='STOCK CHECKLIST',templateConfig={}}){
  const filtered=items.filter(i=>(!movement||i.movement===movement)&&(!category||i.category===category))
  const showCode=templateConfig.show_code===true
  const showUom=templateConfig.show_uom===true
  const showMovement=templateConfig.show_movement===true
  const defs=[
    {key:'no',label:'No.',get:(i,n)=>String(n)},
    ...(showCode?[{key:'code',label:'Code',get:i=>safe(i.item_code)}]:[]),
    {key:'description',label:'Description',get:i=>safe(i.description)},
    {key:'size',label:'Size',get:i=>safe(i.size)},
    ...(showUom?[{key:'uom',label:'UOM',get:i=>safe(i.uom)}]:[]),
    ...(showMovement?[{key:'movement',label:'Movement',get:i=>safe(i.movement)}]:[]),
    {key:'max',label:'Max Stock',get:i=>safe(i.max_stock)},
    {key:'reorder',label:'Reorder Level',get:i=>safe(i.reorder_level)},
    {key:'order',label:'Order',get:()=>''},
  ]
  exportThreeTableStockPdf({
    filename:`GH-${movement||'All'}-Stock-Checklist.pdf`,
    title:`${movement||'ALL'} MOVING STOCK CHECKLIST`,
    subtitle:[category||'All Categories',`${filtered.length} items`].join(' · '),
    company,
    items:filtered,
    rowsPerTable:templateConfig.rows_per_table??10,
    tablesPerPage:templateConfig.tables_per_page??3,
    columns:defs.map(x=>({label:x.label})),
    rowBuilder:(i,n)=>defs.map(x=>x.get(i,n))
  })
}

export function exportStockSheetPdf({items,company,footer,fields=[],title='STOCK CHECK SHEET',stockTaking=false,subtitle=''}) {
  if(stockTaking){
    exportThreeTableStockPdf({
      filename:'GH-Stock-Taking-Sheet.pdf',
      title:'STOCK TAKING SHEET',
      subtitle,
      company,
      items,
      rowsPerTable:10,
      columns:[
        {label:'Description'},
        {label:'Current Stock'},
        {label:'Book Stock'},
        {label:'Variance'},
      ],
      rowBuilder:i=>[
        safe([i.description,i.size].filter(Boolean).join(' · ')),
        '',
        safe(i.book_stock??''),
        ''
      ]
    })
    return
  }

  const doc=new jsPDF({orientation:'landscape',unit:'mm',format:'a4'})
  const startY=addHeader(doc,{title,subtitle,company})
  const cfg=key=>fields.find(f=>f.module_key==='stock'&&f.field_key===key)
  const show=key=>cfg(key)?cfg(key).enabled!==false:true
  const label=(key,fallback)=>cfg(key)?.label||fallback
  const stockDefs=[
    ['item_code','Code',i=>i.item_code],
    ['description','Description',i=>i.description],
    ['main_group','Main Group',i=>i.main_group],
    ['subgroup','Subgroup',i=>i.subgroup],
    ['size','Size',i=>i.size],
    ['uom','UOM',i=>i.uom],
    ['movement','Movement',i=>i.movement],
    ['max_stock','Max Stock',i=>i.max_stock],
    ['reorder_level','Reorder At',i=>i.reorder_level],
    ['current_stock','Current Stock',()=> ''],
    ['remarks','Remarks',i=>i.remarks],
  ].filter(([key])=>show(key))

  autoTable(doc,{
    startY,
    head:[stockDefs.map(([key,fallback])=>label(key,fallback))],
    body:items.map(i=>stockDefs.map(([, ,getter])=>safe(getter(i)))),
    styles:{fontSize:7.2,cellPadding:2.1,minCellHeight:7},
    headStyles:{fillColor:[31,41,55],textColor:255},
    alternateRowStyles:{fillColor:[248,250,252]},
    margin:{left:10,right:10,bottom:20}
  })
  addFooter(doc,footer)
  doc.save('GH-Stock-Check-Sheet.pdf')
}

export function buildCustomStockPdf({items,company,options={},subtitle=''}){
 const cfg=resolveStockPrint(options)
 if(!items?.length)throw new Error('Choose at least one stock item.')
 const doc=new jsPDF({orientation:cfg.orientation,unit:'mm',format:'a4'})
 const pageW=doc.internal.pageSize.getWidth(),pageH=doc.internal.pageSize.getHeight(),margin=10,gap=4
 const defs=STOCK_PRINT_COLUMNS.filter(([key])=>cfg.columns.includes(key)),padding=.8
 const values=items.map((item,index)=>defs.map(([key])=>key==='no'?String(index+1):key==='current_stock'||key==='remarks'?'':safe(item[key])))
 // Measure both bold headings and values before choosing the number of panels.
 const measure=(text,fontSize,bold=false)=>{doc.setFont('helvetica',bold?'bold':'normal');doc.setFontSize(fontSize);return doc.getTextWidth(text)+padding*2}
 const minimum={no:7,uom:8,size:10,current_stock:16,reorder_level:12,remarks:18}
 const required=fontSize=>defs.map(([key,label],n)=>Math.max(minimum[key]||10,measure(label,fontSize,true),...values.map(row=>measure(row[n],fontSize))))
 let panels=cfg.tablesPerPage
 const available=pageW-margin*2
 if(cfg.layout==='columns'){
  const minWidth=required(6).reduce((a,b)=>a+b,0)
  while(panels>1&&(available-gap*(panels-1))/panels<minWidth)panels--
  // A short list should occupy one full-width table, rather than a narrow strip.
  if(items.length<=Math.min(cfg.rowsPerTable||Infinity,Math.floor((pageH-80)/cfg.rowHeight)))panels=1
 }
 const tableW=cfg.layout==='columns'?(available-gap*(panels-1))/panels:available
 let fontSize=cfg.fontSize
 while(fontSize>6&&required(fontSize).reduce((a,b)=>a+b,0)>tableW)fontSize=Math.max(6,fontSize-.25)
 const wanted=required(fontSize),total=wanted.reduce((a,b)=>a+b,0)
 const headerWidths=defs.map(([key,label])=>Math.max(minimum[key]||10,measure(label,6,true)))
 const base=headerWidths.reduce((a,b)=>a+b,0)
 if(base>tableW)throw new Error('Too many columns for this page. Choose fewer columns or landscape orientation.')
 const extra=wanted.map((w,n)=>Math.max(0,w-headerWidths[n])),extraSum=extra.reduce((a,b)=>a+b,0)
 const widths=total<=tableW?wanted.map((w,n)=>w+(tableW-total)*defs[n][2]/defs.reduce((a,c)=>a+c[2],0)):headerWidths.map((w,n)=>w+(tableW-base)*(extraSum?extra[n]/extraSum:1/defs.length))
 const cell=(text,n,header=false)=>{
  const width=widths[n]-padding*2
  let size=fontSize
  while(size>6&&measure(text,size,header)-padding*2>width)size=Math.max(6,size-.25)
  doc.setFont('helvetica',header?'bold':'normal');doc.setFontSize(size)
  const lines=doc.splitTextToSize(text,width)
  return {lines,size,lineHeight:size*.352778*1.18}
 }
 const heads=defs.map((c,n)=>cell(c[1],n,true))
 const headH=Math.max(cfg.rowHeight,...heads.map(c=>c.lines.length*c.lineHeight+padding*2))
 const data=values.map(row=>{const cells=row.map((text,n)=>cell(text,n));return {cells,height:Math.max(cfg.rowHeight,...cells.map(c=>c.lines.length*c.lineHeight+padding*2))}})
 let cursor=0,page=0
 while(cursor<data.length){
  if(page++)doc.addPage()
  doc.setFont('helvetica','bold');doc.setFontSize(12)
  const name=doc.splitTextToSize(company?.name||'General Hardware',pageW-margin*2)
  doc.text(name.slice(0,2),margin,12)
  let top=12+Math.min(name.length,2)*4.7
  doc.setFontSize(10);const title=doc.splitTextToSize(cfg.title||'STOCK CHECK SHEET',pageW-margin*2);doc.text(title.slice(0,2),margin,top);top+=Math.min(title.length,2)*4.2
  doc.setFont('helvetica','normal');doc.setFontSize(7);const sub=doc.splitTextToSize(subtitle,pageW-margin*2);doc.text(sub.slice(0,2),margin,top);top+=Math.min(sub.length,2)*3.2+3
  const space=pageH-top-30,panelH=cfg.layout==='columns'?space:(space-gap*(panels-1))/panels
  const drawRow=(cells,x,y,height,header=false)=>{doc.setFont('helvetica',header?'bold':'normal');let left=x;cells.forEach((cell,n)=>{doc.setFontSize(cell.size);doc.setDrawColor(160);if(header){doc.setFillColor(231,237,243);doc.rect(left,y,widths[n],height,'FD')}else doc.rect(left,y,widths[n],height);doc.setTextColor(20);doc.text(cell.lines,left+padding,y+padding+cell.lineHeight*.82);left+=widths[n]})}
  for(let panel=0;panel<panels&&cursor<data.length;panel++){
   const x=cfg.layout==='columns'?margin+panel*(tableW+gap):margin
   let y=cfg.layout==='columns'?top:top+panel*(panelH+gap),used=headH,count=0
   drawRow(heads,x,y,headH,true);y+=headH
   while(cursor<data.length&&(!cfg.rowsPerTable||count<cfg.rowsPerTable)){
    const row=data[cursor]
    if(row.height+headH>panelH)throw new Error('A description is too long for this table layout. Use fewer tables, side-by-side layout or a smaller font.')
    if(used+row.height>panelH)break
    drawRow(row.cells,x,y,row.height);used+=row.height;y+=row.height;cursor++;count++
   }
  }
 }
 for(let p=1;p<=doc.getNumberOfPages();p++){doc.setPage(p);addStockApprovalFooter(doc);doc.setFontSize(7);doc.text('Page '+p+' of '+doc.getNumberOfPages(),pageW-margin,pageH-7,{align:'right'})}
 return doc
}
