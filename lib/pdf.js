/**
 * Compact company stock count print. Each saved subcategory has its own titled
 * table, while multiple tables can occupy one A4 page (and side-by-side panels).
 * This is strictly presentational: stock data and catalogue rows are read-only.
 */
function buildGroupedStockPdf({items,company,cfg,subtitle,sections=[]}){
 const groups=groupStockPrintRows(items,sections,{includeUncategorized:cfg.includeUncategorized})
 if(!groups.length)throw new Error('No categorized stock items to print.')
 const doc=new jsPDF({orientation:cfg.orientation,unit:'mm',format:'a4'})
 const pageW=doc.internal.pageSize.getWidth(),pageH=doc.internal.pageSize.getHeight()
 const margin=10,gap=4,padding=.8
 const defs=STOCK_PRINT_COLUMNS.filter(([key])=>cfg.columns.includes(key))
 const measure=(text,size,bold=false)=>{doc.setFont('helvetica',bold?'bold':'normal');doc.setFontSize(size);return doc.getTextWidth(safe(text))+padding*2}
 const wordWidth=(text,size,bold=false)=>Math.max(0,...safe(text).split(/\s+/).filter(Boolean).map(w=>measure(w,size,bold)))
 const minimum={no:6,description:27,size:9,uom:8,category:13,subgroup:15,movement:14,max_stock:14,reorder_level:16,current_stock:16,remarks:18,brand:12,colour:12,variation:14}
 const minWidths=defs.map(([key,label])=>Math.max(minimum[key]||12,wordWidth(label,6,true)))
 const available=pageW-margin*2
 let panels=cfg.layout==='columns'&&cfg.splitLongTables?cfg.tablesPerPage:1
 const totalMinimum=minWidths.reduce((a,b)=>a+b,0)
 while(panels>1&&(available-gap*(panels-1))/panels<totalMinimum)panels--
 const tableW=(available-gap*(panels-1))/panels
 if(totalMinimum>tableW)throw new Error('Too many columns for this grouped page. Choose fewer columns or landscape orientation.')
 const wholeHeads=minWidths.map((width,i)=>Math.max(width,measure(defs[i][1],6,true)))
 const widthsBase=wholeHeads.reduce((a,b)=>a+b,0)<=tableW?wholeHeads:minWidths
 const baseTotal=widthsBase.reduce((a,b)=>a+b,0)
 const weights=defs.map(([key,,weight])=>key==='description'?weight*3.5:key==='current_stock'||key==='remarks'?weight*.8:weight)
 const weightTotal=weights.reduce((a,b)=>a+b,0)
 const widths=widthsBase.map((width,i)=>width+(tableW-baseTotal)*weights[i]/weightTotal)
 const cell=(value,index,header=false)=>{
  const text=safe(value),width=widths[index]-padding*2
  const style=cfg.columnStyles[defs[index][0]]
  const bold=header||style.bold
  let size=cfg.fontSize
  while(size>6&&(header?measure(text,size,true):wordWidth(text,size,bold))-padding*2>width)size=Math.max(6,size-.25)
  doc.setFont('helvetica',bold?'bold':'normal');doc.setFontSize(size)
  const lines=doc.splitTextToSize(text,width)
  return {lines,size,bold,align:style.align,lineHeight:size*.352778*1.18}
 }
 const heads=defs.map((definition,i)=>cell(definition[1],i,true))
 const headH=Math.max(cfg.rowHeight,...heads.map(c=>c.lines.length*c.lineHeight+padding*2))
 const prepared=groups.map(group=>({...group,rows:group.items.map((item,index)=>{
  const cells=defs.map(([key],column)=>cell(key==='no'?String(index+1):key==='description'?stockPrintDescription(item,{removeRepeatedSuffix:cfg.removeRepeatedSuffix}):key==='current_stock'||key==='remarks'?'':item[key],column))
  return {cells,height:Math.max(cfg.rowHeight,...cells.map(c=>c.lines.length*c.lineHeight+padding*2))}
 })}))
 function drawRow(cells,x,y,height,header=false){
  let left=x
  cells.forEach((entry,i)=>{
   doc.setFont('helvetica',entry.bold?'bold':'normal');doc.setFontSize(entry.size);doc.setDrawColor(160)
   if(header){doc.setFillColor(231,237,243);doc.rect(left,y,widths[i],height,'FD')}
   else doc.rect(left,y,widths[i],height)
   doc.setTextColor(20)
   const anchor=entry.align==='right'?left+widths[i]-padding:entry.align==='center'?left+widths[i]/2:left+padding
   doc.text(entry.lines,anchor,y+padding+entry.lineHeight*.82,{align:entry.align})
   left+=widths[i]
  })
 }
 let pageCount=0,column=0,top=0,bottom=pageH-31,y=0
 const x=()=>margin+column*(tableW+gap)
 function newPage(){
  if(pageCount++)doc.addPage()
  doc.setFont('helvetica','bold');doc.setFontSize(12)
  const companyLines=doc.splitTextToSize(company?.name||'General Hardware',available).slice(0,2)
  doc.text(companyLines,margin,12)
  let cursor=12+companyLines.length*4.7
  doc.setFontSize(10)
  const titleLines=doc.splitTextToSize(cfg.title||'STOCK CHECK SHEET',available).slice(0,2)
  doc.text(titleLines,margin,cursor);cursor+=titleLines.length*4.2
  doc.setFont('helvetica','normal');doc.setFontSize(7)
  const subtitleLines=doc.splitTextToSize(subtitle,available).slice(0,2)
  if(subtitleLines.length)doc.text(subtitleLines,margin,cursor)
  top=cursor+subtitleLines.length*3.2+4
  column=0;y=top
 }
 function advance(){
  if(column+1<panels){column++;y=top}
  else newPage()
 }
 newPage()
 for(const group of prepared){
  let cursor=0
  while(cursor<group.rows.length){
   const heading=group.title+(cursor?' (continued)':'')
   doc.setFont('helvetica','bold');doc.setFontSize(7.5)
   const headingLines=doc.splitTextToSize(heading,tableW-2*padding)
   const headingH=Math.max(6,headingLines.length*3.2+2)
   const first=group.rows[cursor]
   const required=headingH+headH+first.height
   if(required>bottom-top)throw new Error('A stock item is too tall to fit in a grouped table. Reduce the font or columns.')
   if(y+required>bottom){advance();continue}
   const left=x()
   doc.setFillColor(221,229,237);doc.setDrawColor(150);doc.rect(left,y,tableW,headingH,'FD')
   doc.setFont('helvetica','bold');doc.setFontSize(7.5);doc.setTextColor(20)
   doc.text(headingLines,left+padding,y+3)
   y+=headingH
   drawRow(heads,left,y,headH,true);y+=headH
   let count=0
   while(cursor<group.rows.length&&(!cfg.rowsPerTable||count<cfg.rowsPerTable)){
    const row=group.rows[cursor]
    if(y+row.height>bottom)break
    drawRow(row.cells,left,y,row.height)
    y+=row.height;cursor++;count++
   }
   y+=4
  }
 }
 for(let p=1;p<=doc.getNumberOfPages();p++){
  doc.setPage(p);addStockApprovalFooter(doc)
  doc.setFont('helvetica','normal');doc.setFontSize(7)
  doc.text('Page '+p+' of '+doc.getNumberOfPages(),pageW-margin,pageH-7,{align:'right'})
 }
 return doc
}

export function buildCustomStockPdf({items,company,options={},subtitle='',sections=[]}){
 const cfg=resolveStockPrint(options)
 if(!items?.length)throw new Error('Choose at least one stock item.')
 if(cfg.groupBySubcategory)return buildGroupedStockPdf({items,company,cfg,subtitle,sections})
 const doc=new jsPDF({orientation:cfg.orientation,unit:'mm',format:'a4'})
 const pageW=doc.internal.pageSize.getWidth(),pageH=doc.internal.pageSize.getHeight(),margin=10,gap=4
 const defs=STOCK_PRINT_COLUMNS.filter(([key])=>cfg.columns.includes(key)),padding=.8
 const values=items.map((item,index)=>defs.map(([key])=>key==='no'?String(index+1):key==='description'?stockPrintDescription(item,{removeRepeatedSuffix:cfg.removeRepeatedSuffix}):key==='current_stock'||key==='remarks'?'':safe(item[key])))
 // Allow headers and descriptions to wrap when assessing whether two printable panels fit.
 // Measuring the entire description as an unbreakable line falsely forced long lists to one panel.
 const measure=(text,fontSize,bold=false)=>{doc.setFont('helvetica',bold?'bold':'normal');doc.setFontSize(fontSize);return doc.getTextWidth(safe(text))+padding*2}
 const widestWord=(text,fontSize,bold=false)=>Math.max(0,...safe(text).split(/\s+/).filter(Boolean).map(word=>measure(word,fontSize,bold)))
 const minimum={no:6,description:27,size:9,uom:8,category:13,subgroup:15,movement:14,max_stock:14,reorder_level:16,current_stock:16,remarks:18,brand:12,colour:12,variation:14}
 const minWidths=defs.map(([key,label])=>Math.max(minimum[key]||12,widestWord(label,6,true)))
 const minTotal=minWidths.reduce((a,b)=>a+b,0)
 const available=pageW-margin*2
 let panels=cfg.splitLongTables?cfg.tablesPerPage:1
 if(cfg.layout==='columns'){
  // "Maximum" is a limit: short lists remain easy to read in one full-width table.
  const shortListCapacity=Math.floor((pageH-80)/cfg.rowHeight)
  if(items.length<=Math.min(cfg.rowsPerTable||Infinity,shortListCapacity))panels=1
  while(panels>1&&(available-gap*(panels-1))/panels<minTotal)panels--
 }
 const tableW=cfg.layout==='columns'?(available-gap*(panels-1))/panels:available
 if(minTotal>tableW)throw new Error('Too many columns for this page. Choose fewer columns or landscape orientation.')
 // On wider sheets, reserve enough width for each full heading at 6 pt; only narrow panels wrap.
 const wholeHeadWidths=minWidths.map((w,n)=>Math.max(w,measure(defs[n][1],6,true)))
 const wholeHeadTotal=wholeHeadWidths.reduce((a,b)=>a+b,0)
 const baseWidths=wholeHeadTotal<=tableW?wholeHeadWidths:minWidths
 const baseTotal=baseWidths.reduce((a,b)=>a+b,0)
 // Distribute remaining width towards the description instead of reserving a whole unwrapped
 // sentence in every panel. This keeps the writing and quantity columns usable.
 const priorities=defs.map(([key,,weight])=>key==='description'?weight*3.5:key==='current_stock'||key==='remarks'?weight*.8:weight)
 const priorityTotal=priorities.reduce((a,b)=>a+b,0)
 const widths=baseWidths.map((w,n)=>w+(tableW-baseTotal)*priorities[n]/priorityTotal)
 const cell=(text,n,header=false)=>{
  const width=widths[n]-padding*2
  const style=cfg.columnStyles[defs[n][0]]
  const bold=header||style.bold
  let size=cfg.fontSize
  // Shrink only when needed; measure bold print text with its real font metrics.
  while(size>6&&(header?measure(text,size,true):widestWord(text,size,bold))-padding*2>width)size=Math.max(6,size-.25)
  doc.setFont('helvetica',bold?'bold':'normal');doc.setFontSize(size)
  const lines=doc.splitTextToSize(text,width)
  return {lines,size,bold,align:style.align,lineHeight:size*.352778*1.18}
 }
 const heads=defs.map((c,n)=>cell(c[1],n,true))
 const headH=Math.max(cfg.rowHeight,...heads.map(c=>c.lines.length*c.lineHeight+padding*2))
 const data=values.map(row=>{const cells=row.map((text,n)=>cell(text,n));return {cells,height:Math.max(cfg.rowHeight,...cells.map(c=>c.lines.length*c.lineHeight+padding*2))}})
 let cursor=0,page=0
 while(cursor<data.length){
  if(page++)doc.addPage()
  doc.setFont('helvetica','bold');doc.setFontSize(12)
  const name=doc.splitTextToSize(company?.name||'General Hardware',pageW-margin*2)
  doc.text(name.slice(0,2),margin,12)
  let top=12+Math.min(name.length,2)*4.7
  doc.setFontSize(10);const title=doc.splitTextToSize(cfg.title||'STOCK CHECK SHEET',pageW-margin*2);doc.text(title.slice(0,2),margin,top);top+=Math.min(title.length,2)*4.2
  doc.setFont('helvetica','normal');doc.setFontSize(7);const sub=doc.splitTextToSize(subtitle,pageW-margin*2);doc.text(sub.slice(0,2),margin,top);top+=Math.min(sub.length,2)*3.2+3
  const space=pageH-top-30,panelH=cfg.layout==='columns'?space:(space-gap*(panels-1))/panels
  const drawRow=(cells,x,y,height,header=false)=>{let left=x;cells.forEach((cell,n)=>{doc.setFont('helvetica',cell.bold?'bold':'normal');doc.setFontSize(cell.size);doc.setDrawColor(160);if(header){doc.setFillColor(231,237,243);doc.rect(left,y,widths[n],height,'FD')}else doc.rect(left,y,widths[n],height);doc.setTextColor(20);const anchor=cell.align==='right'?left+widths[n]-padding:cell.align==='center'?left+widths[n]/2:left+padding;doc.text(cell.lines,anchor,y+padding+cell.lineHeight*.82,{align:cell.align});left+=widths[n]})}
  for(let panel=0;panel<panels&&cursor<data.length;panel++){
   const x=cfg.layout==='columns'?margin+panel*(tableW+gap):margin
   let y=cfg.layout==='columns'?top:top+panel*(panelH+gap),used=headH,count=0
   drawRow(heads,x,y,headH,true);y+=headH
   while(cursor<data.length&&(!cfg.rowsPerTable||count<cfg.rowsPerTable)){
    const row=data[cursor]
    if(row.height+headH>panelH)throw new Error('A description is too long for this table layout. Use fewer tables, side-by-side layout or a smaller font.')
    if(used+row.height>panelH)break
    drawRow(row.cells,x,y,row.height);used+=row.height;y+=row.height;cursor++;count++
   }
  }
 }
 for(let p=1;p<=doc.getNumberOfPages();p++){doc.setPage(p);addStockApprovalFooter(doc);doc.setFontSize(7);doc.text('Page '+p+' of '+doc.getNumberOfPages(),pageW-margin,pageH-7,{align:'right'})}
 return doc
}
