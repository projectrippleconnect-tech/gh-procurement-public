-- Run only against the isolated full schema. All synthetic records roll back.
begin;
create temporary table submit_boundary_results(check_name text,passed boolean);
grant insert,select on submit_boundary_results to authenticated;
do $$
declare admin uuid;staff uuid:=gen_random_uuid();company uuid;line uuid;result_v jsonb;before_v bigint;denied boolean;
 body jsonb;no_lists_role text:='qa_count_only_'||replace(gen_random_uuid()::text,'-','');
begin
 select id into strict admin from public.proc_profiles where role_key='admin' and active limit 1;
 perform set_config('request.jwt.claim.sub',admin::text,true);
 result_v:=public.proc_company_import_sheet('QA submit boundaries',987654321,jsonb_build_array(jsonb_build_object('source_key','qa:count:one','description','QA boundary item','category','GENERAL','uom','PCS','max_stock',10)));
 company:=(result_v->>'company_id')::uuid;
 select id into strict line from public.proc_company_list_items where company_id=company;
 body:=jsonb_build_array(jsonb_build_object('company_list_item_id',line,'current_stock',0));
 select count(*) into before_v from public.proc_stock_counts;
 denied:=false;begin perform public.proc_submit_company_list_check_v2(company,null);exception when others then denied:=true;end;
 assert denied,'Null payload created an empty count';
 denied:=false;begin perform public.proc_submit_company_list_check_v2(company,body,NULL,now()+interval '1 day');exception when others then denied:=true;end;
 assert denied,'Future-dated count bypassed stale-stock checks';
 denied:=false;begin perform public.proc_submit_company_list_check_v2(company,body||body);exception when others then denied:=true;end;
 assert denied,'Duplicate item payload accepted';
 assert (select count(*)=before_v from public.proc_stock_counts),'Rejected payload left a partial count';
 insert into submit_boundary_results values('Null, future-dated and duplicate company counts rejected atomically',true);
 insert into auth.users(id,email) values(staff,'count-'||staff||'@example.invalid');
 insert into public.proc_profiles(id,role,role_key,display_name) values(staff,'stock_handler','stock_handler','Isolated stock handler');
 perform set_config('request.jwt.claim.sub',staff::text,true);
 execute 'set local role authenticated';
 result_v:=public.proc_submit_company_list_check_v2(company,body);
 assert (result_v->>'requirements_created')::integer=1,'Legacy staff count did not compute shortage';
 assert (select counted_by=staff from public.proc_stock_counts where id=(result_v->>'count_id')::uuid),'Submission lost its real caller';
 assert not has_function_privilege('authenticated','private.proc_company_effective_route(uuid,uuid)','EXECUTE'),'Private route lookup was opened to clients';
 assert not (select prosecdef from pg_proc where oid='public.proc_submit_company_list_check_v2(uuid,jsonb,text,timestamptz)'::regprocedure),'Public legacy wrapper must remain an invoker';
 insert into submit_boundary_results values('Authorized legacy staff submission works without exposing internal routing',true);
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',admin::text,true);
 insert into public.proc_roles(role_key,name,base_role) values(no_lists_role,'Isolated count-only role','stock_handler');
 insert into public.proc_role_permissions(role_key,permission_key,allowed) values(no_lists_role,'stock.count.enter',true);
 update public.proc_profiles set role_key=no_lists_role where id=staff;
 perform set_config('request.jwt.claim.sub',staff::text,true);
 execute 'set local role authenticated';
 denied:=false;begin perform public.proc_submit_company_list_check_v2(company,body);exception when others then denied:=true;end;
 assert denied,'Count-only role without company-list access submitted company stock';
 execute 'reset role';execute 'set local role anon';
 denied:=false;begin perform public.proc_submit_company_list_check_v2(company,body);exception when insufficient_privilege then denied:=true;end;
 assert denied,'Anonymous caller executed legacy submit';
 execute 'reset role';
 insert into submit_boundary_results values('Missing company-list permission and anonymous callers rejected',true);
end $$;
select * from submit_boundary_results;
rollback;
