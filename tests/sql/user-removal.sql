-- Uses only a newly-created fixture account. All changes roll back.
begin;
set local statement_timeout='30s';
do $test$
declare admin_id uuid; fixture_id uuid:=gen_random_uuid(); history_id uuid:=gen_random_uuid(); denied boolean; result jsonb; visible bigint;
begin
 select id into strict admin_id from public.proc_profiles where active and role_key='admin' and deleted_at is null limit 1;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 insert into auth.users(id,email,raw_app_meta_data,raw_user_meta_data) values(fixture_id,'removal-'||fixture_id||'@example.invalid','{}','{}');
 insert into public.app_users(id,email,display_name,active,custom_data) values(fixture_id,'removal-'||fixture_id||'@example.invalid','Removal test',true,'{"gh_procurement_access":true,"other_app_setting":"preserve"}') on conflict(id) do update set active=true,custom_data=excluded.custom_data;
 insert into public.proc_profiles(id,display_name,role,role_key,active) values(fixture_id,'Removal test','viewer','viewer',true);
 insert into public.proc_user_directory(user_id,email,display_name) values(fixture_id,'removal-'||fixture_id||'@example.invalid','Removal test');
 insert into public.proc_user_invites(email,display_name,role,role_key,status,invited_by,invited_user_id) values('removal-'||fixture_id||'@example.invalid','Removal test','viewer','viewer','pending',admin_id,fixture_id);
 insert into public.proc_rfqs(id,rfq_no,created_by) values(history_id,'REMOVAL-TEST-'||history_id,fixture_id);
 denied:=false;
 begin perform public.proc_admin_delete_user_v1(admin_id,'DELETE ADMIN');exception when others then denied:=true;end;
 if not denied then raise exception 'Self deletion accepted';end if;
 denied:=false;
 begin perform public.proc_admin_delete_user_v1(fixture_id,'DELETE WRONG');exception when others then denied:=true;end;
 if not denied then raise exception 'Incorrect confirmation accepted';end if;
 perform set_config('request.jwt.claim.sub',fixture_id::text,true);
 denied:=false;
 begin perform public.proc_admin_delete_user_v1(admin_id,'DELETE ADMIN');exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Viewer deleted a user';end if;
 perform set_config('request.jwt.claim.sub','',true);
 denied:=false;
 begin perform public.proc_admin_delete_user_v1(fixture_id,'DELETE Removal test');exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Unauthenticated deletion accepted';end if;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 result:=public.proc_admin_delete_user_v1(fixture_id,'DELETE Removal test');
 if result->>'ok'<>'true' then raise exception 'Deletion unsuccessful';end if;
 if not exists(select 1 from public.proc_profiles where id=fixture_id and not active and deleted_at is not null and deleted_by=admin_id) then raise exception 'Missing deletion marker';end if;
 if not exists(select 1 from auth.users where id=fixture_id) then raise exception 'Shared identity deleted';end if;
 if not exists(select 1 from public.app_users where id=fixture_id and active and custom_data->>'gh_procurement_access'='false' and custom_data->>'other_app_setting'='preserve') then raise exception 'Shared-app access or settings damaged';end if;
 if not exists(select 1 from public.proc_rfqs where id=history_id and created_by=fixture_id) then raise exception 'Historical procurement record lost';end if;
 if exists(select 1 from public.proc_user_invites where invited_user_id=fixture_id and status='pending') then raise exception 'Pending invitation remains';end if;
 if exists(select 1 from public.proc_user_directory where user_id=fixture_id) then raise exception 'User directory still contains removed user';end if;
 if not exists(select 1 from public.proc_audit_logs where record_id=fixture_id and action='DELETE' and user_id=admin_id) then raise exception 'Missing deletion audit';end if;
 perform set_config('request.jwt.claim.sub',fixture_id::text,true);
 if private.proc_has_permission('dashboard.view') or private.proc_is_role(array['viewer']) then raise exception 'Deleted user retains authorization';end if;
 denied:=false;
 begin perform public.proc_ensure_profile();exception when others then denied:=true;end;
 if not denied then raise exception 'Deleted user can recreate access';end if;
 execute 'set local role authenticated';
 select count(*) into visible from public.proc_rfqs;
 if visible<>0 then raise exception 'Existing user JWT can read procurement records';end if;
 execute 'reset role';
 raise notice 'PASS self/permission/confirmation guards, deletion audit, invitation revocation, shared-app/history preservation, bootstrap denial and existing-session RLS denial';
end $test$;
rollback;
