import test from 'node:test'
import assert from 'node:assert/strict'
import {PGlite} from '@electric-sql/pglite'
import {pgcrypto} from '@electric-sql/pglite/contrib/pgcrypto'
import {bootstrapProcurementSchema} from '../scripts/qa/schema-bootstrap.mjs'
import {newlyArrivedNotifications,notificationDestination,isOpenIssue} from '../lib/notification-state.mjs'

test('notification presentation suppresses initial history, resolved and postponed events; links carry source records',()=>{
 const a={id:'a',title:'Price returned',target_view:'rfq',record_id:'source'}
 assert.deepEqual(newlyArrivedNotifications(null,[a]),[])
 assert.deepEqual(newlyArrivedNotifications(new Set(),[a,{id:'b',resolved_at:'2026-01-01'},{id:'c',snoozed_until:'2099-01-01'}]),[a])
 assert.deepEqual(notificationDestination(a),{view:'rfq',filter:'source'})
 assert.equal(notificationDestination({target_view:'https://evil.invalid'}).view,'urgent_actions')
 assert.equal(isOpenIssue({issue_key:'x',snoozed_until:'2099-01-01'}),false)
})

test('actual notification DB lifecycle: source events, issue resolution, audited postponement, RLS and atomic push claims',async()=>{
 const db=new PGlite({extensions:{pgcrypto}})
 const q=async(sql,args=[])=> (await db.query(sql,args)).rows
 const one=async(sql,args=[])=> (await q(sql,args))[0]
 const adminId='00000000-0000-4000-8000-000000000111'
 try{
  await bootstrapProcurementSchema(db)
  const supplier=await one("insert into public.proc_suppliers(supplier_code,name) values('NOTIFY-QA','Notification Supplier') returning id")
  const item=await one("insert into public.proc_items(item_code,category,description,uom) values('NOTIFY-QA','QA','Notification item','PCS') returning id")
  const req=await one("insert into public.proc_requirements(item_id,location_id,required_qty,adjusted_qty,approval_status,selected_for_order) values($1,'00000000-0000-4000-8000-000000000099',10,10,'approved',true) returning id",[item.id])
  const rfq=await one("insert into public.proc_rfqs(rfq_no,status,due_date) values('NOTIFY-QA','sent',current_date-2) returning id")
  const ri=await one('insert into public.proc_rfq_items(rfq_id,requirement_id,requested_qty) values($1,$2,10) returning id',[rfq.id,req.id])
  const inv=await one("insert into public.proc_rfq_suppliers(rfq_id,supplier_id,status,sent_at) values($1,$2,'sent',now()-interval '2 days') returning id",[rfq.id,supplier.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  const keys=await q('select kind from public.proc_admin_notifications where issue_key is not null and resolved_at is null')
  assert.ok(keys.some(n=>n.kind==='no_response'));assert.ok(keys.some(n=>n.kind==='insufficient_quotes'))
  const count=Number((await one('select count(*) n from public.proc_admin_notifications')).n)
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal(Number((await one('select count(*) n from public.proc_admin_notifications')).n),count,'continuous issues do not repeat each minute')
  const issue=await one("select * from public.proc_admin_notifications where kind='no_response'")
  await db.exec('set role authenticated')
  await q('select public.proc_notification_postpone_v1($1,4,$2)',[issue.id,'Waiting for supplier callback'])
  assert.ok((await one('select snoozed_until from public.proc_admin_notifications where id=$1',[issue.id])).snoozed_until)
  await assert.rejects(q('update public.proc_admin_notifications set title=$1 where id=$2',['Forged',issue.id]),/permission denied/)
  await assert.rejects(q('select * from public.proc_push_claim_v1(10)'),/permission denied/)
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000999',false)")
  assert.equal((await q('select * from public.proc_admin_notifications')).length,0,'another user cannot read admin alerts')
  await assert.rejects(q('select public.proc_notification_postpone_v1($1,4,$2)',[issue.id,'Unauthorized attempt']),/Administrator required/)
  await db.exec(`reset role;select set_config('request.jwt.claim.sub','${adminId}',false)`)
  assert.equal(Number((await one("select count(*) n from public.proc_audit_logs where action='notification_postponed'")).n),1)
  await db.exec('begin')
  const quote=await one("insert into public.proc_quotes(rfq_id,supplier_id,valid_until) values($1,$2,current_date-1) returning id",[rfq.id,supplier.id])
  await q('insert into public.proc_quote_lines(quote_id,rfq_item_id,unit_price,available_qty,moq) values($1,$2,10,10,20)',[quote.id,ri.id])
  const priceEvents=await q("select * from public.proc_admin_notifications where kind='supplier_prices'")
  assert.equal(priceEvents.length,1,'header plus lines in one save create one price event')
  assert.equal(priceEvents[0].record_id,rfq.id)
  await db.exec('commit')
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.ok((await q("select * from public.proc_admin_notifications where kind='expired_quote' and resolved_at is null")).length)
  await q("update public.proc_quotes set valid_until=current_date+3 where id=$1",[quote.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.ok((await q("select * from public.proc_admin_notifications where kind='overbuy' and resolved_at is null")).length)
  assert.equal((await q("select * from public.proc_admin_notifications where kind='expired_quote' and resolved_at is null")).length,0,'renewing a quote clears its expired issue')
  await q("update public.proc_rfq_suppliers set status='quoted' where id=$1",[inv.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal((await q("select * from public.proc_admin_notifications where kind='no_response' and resolved_at is null")).length,0)
  await q("update public.proc_rfq_suppliers set status='sent',sent_at=now()-interval '2 days' where id=$1",[inv.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal(Number((await one("select count(*) n from public.proc_admin_notifications where kind='no_response'")).n),2,'recurrence creates a new issue episode')
  const po=await one("insert into public.proc_purchase_orders(po_no,supplier_id,status,expected_date) values('NOTIFY-PO',$1,'pending_approval',current_date-1) returning id",[supplier.id])
  await q('insert into public.proc_po_lines(po_id,item_id,requirement_id,qty,unit_price) values($1,$2,$3,10,10)',[po.id,item.id,req.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal((await q("select * from public.proc_admin_notifications where kind='unapproved_cost' and resolved_at is null")).length,1,'PO submission and approval issue share one notification')
  await q("update public.proc_purchase_orders set status='approved',approved_by=$2,approved_at=now() where id=$1",[po.id,adminId])
  await q("update public.proc_purchase_orders set status='sent',sent_at=now() where id=$1",[po.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.ok((await q("select * from public.proc_admin_notifications where kind='delayed_delivery' and resolved_at is null")).length)
  assert.equal((await q("select * from public.proc_admin_notifications where kind='unapproved_cost' and resolved_at is null")).length,0)
  const invoice=await one("insert into public.proc_supplier_invoices(supplier_id,po_id,invoice_no,status,variance_resolution_status) values($1,$2,'NOTIFY-INVOICE','variance','open') returning id",[supplier.id,po.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.ok((await q("select * from public.proc_admin_notifications where kind='invoice_variance' and resolved_at is null")).length)
  await q("update public.proc_supplier_invoices set variance_resolution_status='resolved' where id=$1",[invoice.id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal((await q("select * from public.proc_admin_notifications where kind='invoice_variance' and resolved_at is null")).length,0)

  // Registration times avoid replaying historical alerts. Build a backlog past the old 200-row cutoff.
  await q("insert into public.proc_push_subscriptions(user_id,endpoint,subscription,created_at) values($1,'https://fcm.googleapis.com/qa-only','{\"endpoint\":\"https://fcm.googleapis.com/qa-only\"}',now()-interval '1 hour')",[adminId])
  await q("update public.proc_admin_notifications set read_at=now()")
  await q("insert into public.proc_admin_notifications(recipient_id,event_key,kind,title,body,target_view) select $1,'backlog:'||g,'qa','Fixture','No network traffic','rfq' from generate_series(1,205) g",[adminId])
  await db.exec('set role service_role')
  const first=await q('select * from public.proc_push_claim_v1(100)');assert.equal(first.length,100)
  const second=await q('select * from public.proc_push_claim_v1(100)');assert.equal(second.length,100)
  assert.equal(new Set([...first,...second].map(x=>x.notification_id)).size,200,'leases exclude already claimed rows')
  assert.equal((await q('select * from public.proc_push_claim_v1(100)')).length,5,'later rows are not starved by delivered history')
  assert.equal((await q('select * from public.proc_push_claim_v1(100)')).length,0)
  await db.exec('reset role')
  const id=first[0].notification_id
  await q("update public.proc_push_deliveries set attempts=5,next_attempt_at=now()-interval '1 minute' where notification_id=$1",[id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.ok((await q("select * from public.proc_admin_notifications where kind='failed_notification' and resolved_at is null")).length)
  await q("update public.proc_push_deliveries set sent_at=now() where notification_id=$1",[id])
  await db.exec('select private.proc_reconcile_notification_issues()')
  assert.equal((await q("select * from public.proc_admin_notifications where kind='failed_notification' and resolved_at is null")).length,0)
  await db.exec('set role anon')
  await assert.rejects(q('select * from public.proc_admin_notifications'),/permission denied/)
  await assert.rejects(q('select public.proc_notification_postpone_v1($1,4,$2)',[issue.id,'Not allowed']),/permission denied/)
 }finally{await db.close()}
})
