import test from 'node:test'
import assert from 'node:assert/strict'
import {PGlite} from '@electric-sql/pglite'
import {pgcrypto} from '@electric-sql/pglite/contrib/pgcrypto'
import {bootstrapProcurementSchema} from '../scripts/qa/schema-bootstrap.mjs'

test('verified supplier accounts enforce OTP ownership, limits, expiry and approved standing-price reuse',async()=>{
 const db=new PGlite({extensions:{pgcrypto}})
 const one=async(q,p=[])=> (await db.query(q,p)).rows[0]
 const rpc=async(name,args)=> (await one('select public.'+name+'('+args.map((_,i)=>'$'+(i+1)).join(',')+') result',args)).result
 const admin=()=>db.exec('reset role')
 const anon=()=>db.exec('set role anon')
 try{
  await bootstrapProcurementSchema(db)
  const supplier=await one("insert into public.proc_suppliers(supplier_code,name,phone,supplier_kind) values('VERIFY-QA','Verified supplier','+94770000123','company') returning id")
  const item=await one("insert into public.proc_items(item_code,category,description,size,uom) values('VERIFY-QA','QA','Verified item','2 inch','PCS') returning id")
  const req=await one("insert into public.proc_requirements(item_id,location_id,required_qty,adjusted_qty,approval_status,selected_for_order) values($1,'00000000-0000-4000-8000-000000000099',10,10,'approved',true) returning id",[item.id])
  const rfq=await one("insert into public.proc_rfqs(rfq_no,status) values('VERIFY-QA','sent') returning id")
  const line=await one('insert into public.proc_rfq_items(rfq_id,requirement_id,requested_qty) values($1,$2,10) returning id',[rfq.id,req.id])
  const invitation=await one("insert into public.proc_rfq_suppliers(rfq_id,supplier_id,status) values($1,$2,'sent') returning id",[rfq.id,supplier.id])
  const hash=async token=>(await one("select encode(extensions.digest($1,'sha256'),'hex') hash",[token])).hash
  const token='a'.repeat(64)
  await rpc('proc_portal_issue_verified_link_v1',[invitation.id,await hash(token),6])
  await anon()
  assert.deepEqual(await rpc('proc_portal_read_v1',[token]),{verification_required:true})
  await assert.rejects(rpc('proc_portal_submit_v1',[token,'[]',0,false]),/verification required/)
  await assert.rejects(one('select * from private.proc_supplier_challenges'),/permission denied/)
  assert.equal((await rpc('proc_supplier_request_code_v1',[token,'0770000999'])).ok,false)
  const challenge=await rpc('proc_supplier_request_code_v1',[token,'0770000123'])
  assert.equal(challenge.ok,true);assert.equal(challenge.code,undefined)
  assert.equal((await rpc('proc_supplier_request_code_v1',[token,'0770000123'])).ok,false,'cooldown persists server-side')
  await assert.rejects(rpc('proc_supplier_issue_code_v1',[challenge.challenge_id]),/permission denied/)
  await admin()
  const issued=await rpc('proc_supplier_issue_code_v1',[challenge.challenge_id])
  assert.match(issued.code,/^\d{6}$/);assert.equal(issued.phone,'+94770000123')
  await assert.rejects(rpc('proc_supplier_issue_code_v1',[challenge.challenge_id]),/already issued/)
  await anon()
  assert.equal((await rpc('proc_supplier_verify_code_v1',[token,challenge.challenge_id,issued.code])).ok,false,'not usable before staff records directory-phone delivery')
  await admin();await rpc('proc_supplier_mark_code_sent_v1',[challenge.challenge_id]);await anon()
  const wrong=issued.code==='000000'?'111111':'000000'
  assert.equal((await rpc('proc_supplier_verify_code_v1',[token,challenge.challenge_id,wrong])).attempts_remaining,4)
  const verified=await rpc('proc_supplier_verify_code_v1',[token,challenge.challenge_id,issued.code])
  assert.equal(verified.ok,true)
  assert.equal((await rpc('proc_supplier_verify_code_v1',[token,challenge.challenge_id,issued.code])).ok,false,'single-use OTP')
  const quote=await rpc('proc_supplier_quote_read_v1',[token,verified.session,null])
  assert.equal(quote.items[0].id,line.id)
  await assert.rejects(rpc('proc_supplier_quote_read_v1',[token,'b'.repeat(64),null]),/verification required/)
  const response=JSON.stringify([{id:line.id,status:'in_stock',price:12,quantity:4,uom:'PCS',terms_confirmed:false,variations:[]}])
  assert.equal((await rpc('proc_supplier_quote_submit_v1',[token,verified.session,null,response,0,true])).revision,1)
  await assert.rejects(rpc('proc_supplier_quote_submit_v1',[token,verified.session,null,response,0,false]),/changed|revision|Reload/i)
  await admin()
  await db.query("update public.proc_suppliers set phone='+94770000999' where id=$1",[supplier.id])
  await anon();await assert.rejects(rpc('proc_supplier_quote_read_v1',[token,verified.session,null]),/verification required/)
  await admin();await db.query("update public.proc_suppliers set phone='+94770000123' where id=$1",[supplier.id])
  await anon();await assert.rejects(rpc('proc_supplier_quote_read_v1',[token,verified.session,null]),/verification required/,'changing a phone back cannot revive the old session');await admin()

  const account='c'.repeat(64)
  await rpc('proc_supplier_account_issue_v1',[supplier.id,await hash(account),false])
  await db.exec("update private.proc_supplier_challenges set created_at=clock_timestamp()-interval '2 minutes'")
  await anon();const ac=await rpc('proc_supplier_request_code_v1',[account,'+94770000123']);await admin()
  const acode=await rpc('proc_supplier_issue_code_v1',[ac.challenge_id]);await rpc('proc_supplier_mark_code_sent_v1',[ac.challenge_id]);await anon()
  const login=await rpc('proc_supplier_verify_code_v1',[account,ac.challenge_id,acode.code])
  await admin()
  const secret=await one("insert into public.proc_items(item_code,category,description,uom) values('PRIVATE-DRAFT-QA','QA','Unpublished item','PCS') returning id")
  const secretReq=await one("insert into public.proc_requirements(item_id,location_id,required_qty,adjusted_qty,approval_status,selected_for_order) values($1,'00000000-0000-4000-8000-000000000099',2,2,'approved',true) returning id",[secret.id])
  const secretRfq=await one("insert into public.proc_rfqs(rfq_no,status) values('UNSENT-QA','draft') returning id")
  await db.query('insert into public.proc_rfq_items(rfq_id,requirement_id,requested_qty) values($1,$2,2)',[secretRfq.id,secretReq.id])
  const secretInv=await one("insert into public.proc_rfq_suppliers(rfq_id,supplier_id,status) values($1,$2,'pending') returning id",[secretRfq.id,supplier.id])
  await rpc('proc_portal_issue_verified_link_v1',[secretInv.id,await hash('f'.repeat(64)),6])
  await anon()
  const home=await rpc('proc_supplier_account_read_v1',[account,login.session])
  assert.equal(home.requests[0].invitation,invitation.id);assert.equal(home.items.length,1)
  assert.equal(home.requests.length,1,'Reusable access must not discover an unsent draft invitation, even if staff prepared a private link')
  await assert.rejects(rpc('proc_supplier_quote_read_v1',[account,login.session,secretInv.id]),/invitation unavailable/)
  await assert.rejects(rpc('proc_supplier_standing_save_v1',[account,login.session,null,0,JSON.stringify([{item_id:secret.id,uom:'PCS',price:1,quantity:2}]),new Date(Date.now()+86400000).toISOString(),false]),/Uninvited/)
  assert.equal((await rpc('proc_supplier_quote_read_v1',[account,login.session,invitation.id])).revision,1)
  await assert.rejects(rpc('proc_supplier_quote_read_v1',[account,login.session,'00000000-0000-4000-8000-000000000999']),/invitation unavailable/)
  const standing=JSON.stringify([{item_id:item.id,uom:'PCS',price:14,quantity:8,notes:'Blue'}])
  const expiry=new Date(Date.now()+86400000).toISOString()
  const draft=await rpc('proc_supplier_standing_save_v1',[account,login.session,null,0,standing,expiry,false])
  await assert.rejects(rpc('proc_supplier_standing_save_v1',[account,login.session,draft.id,0,standing,expiry,true]),/version changed/)
  const submitted=await rpc('proc_supplier_standing_save_v1',[account,login.session,draft.id,1,standing,expiry,true])
  await assert.rejects(rpc('proc_supplier_standing_review_v1',[draft.id,2,true]),/permission denied/)
  await admin()
  assert.equal((await rpc('proc_supplier_standing_review_v1',[draft.id,submitted.revision,true])).state,'approved')
  const rfq2=await one("insert into public.proc_rfqs(rfq_no,status) values('VERIFY-QA-2','sent') returning id")
  const req2=await one("insert into public.proc_requirements(item_id,location_id,required_qty,adjusted_qty,approval_status,selected_for_order) values($1,'00000000-0000-4000-8000-000000000099',10,10,'approved',true) returning id",[item.id])
  await db.query('insert into public.proc_rfq_items(rfq_id,requirement_id,requested_qty) values($1,$2,10)',[rfq2.id,req2.id])
  const inv2=await one("insert into public.proc_rfq_suppliers(rfq_id,supplier_id,status) values($1,$2,'sent') returning id",[rfq2.id,supplier.id])
  const token2='d'.repeat(64);await rpc('proc_portal_issue_verified_link_v1',[inv2.id,await hash(token2),6])
  const reused=await rpc('proc_supplier_standing_reuse_v1',[draft.id,inv2.id,0])
  assert.equal(reused.status,'draft');assert.equal(Number((await one('select count(*) n from public.proc_purchase_orders')).n),0)
  const stored=await one('select response,status from public.proc_supplier_portal_links where rfq_supplier_id=$1',[inv2.id])
  assert.equal(stored.response[0].terms_confirmed,false)
  assert.match(stored.response[0].notes,/Blue/,'Reuse retains supplier remarks')
  await assert.rejects(rpc('proc_supplier_standing_reuse_v1',[draft.id,inv2.id,0]),/empty, current/)
  await db.query("update private.proc_supplier_standing_prices set valid_until=clock_timestamp()-interval '1 minute' where id=$1",[draft.id])
  await assert.rejects(rpc('proc_supplier_standing_reuse_v1',[draft.id,inv2.id,1]),/empty, current/)
  await db.exec("update private.proc_supplier_challenges set created_at=clock_timestamp()-interval '2 minutes'")
  await anon();const limited=await rpc('proc_supplier_request_code_v1',[account,'+94770000123']);await admin()
  const limitCode=await rpc('proc_supplier_issue_code_v1',[limited.challenge_id]);await rpc('proc_supplier_mark_code_sent_v1',[limited.challenge_id]);await anon()
  for(let i=0;i<5;i++)assert.equal((await rpc('proc_supplier_verify_code_v1',[account,limited.challenge_id,limitCode.code==='000000'?'111111':'000000'])).ok,false)
  assert.equal((await rpc('proc_supplier_verify_code_v1',[account,limited.challenge_id,limitCode.code])).ok,false,'five wrong attempts persist and block even a later correct code')
  await admin();await db.query("update private.proc_supplier_challenges set attempts=0,expires_at=clock_timestamp()-interval '1 second' where id=$1",[limited.challenge_id]);await anon()
  assert.equal((await rpc('proc_supplier_verify_code_v1',[account,limited.challenge_id,limitCode.code])).ok,false,'expired code is rejected even when correct')
  await admin();await db.query("update private.proc_supplier_sessions set expires_at=clock_timestamp()-interval '1 minute' where supplier_id=$1",[supplier.id]);await anon()
  await assert.rejects(rpc('proc_supplier_account_read_v1',[account,login.session]),/verification required/)
  await admin()
  await db.exec("update private.proc_supplier_challenges set created_at=clock_timestamp()-interval '2 minutes'")
  await anon();const lc=await rpc('proc_supplier_request_code_v1',[account,'0770000123']);await admin()
  const lcode=await rpc('proc_supplier_issue_code_v1',[lc.challenge_id]);await rpc('proc_supplier_mark_code_sent_v1',[lc.challenge_id]);await anon()
  const ls=await rpc('proc_supplier_verify_code_v1',[account,lc.challenge_id,lcode.code]);assert.equal(ls.ok,true)
  await rpc('proc_supplier_logout_v1',[account,ls.session]);await assert.rejects(rpc('proc_supplier_account_read_v1',[account,ls.session]),/verification required/)
  await admin()
  await rpc('proc_supplier_account_issue_v1',[supplier.id,null,true])
  await anon();await assert.rejects(rpc('proc_supplier_account_read_v1',[account,login.session]),/verification required/)
 }finally{await db.close()}
})
